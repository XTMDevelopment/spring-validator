package id.xtramile.validator.enums;

/**
 * Units for measuring distance between two date-times.
 */
public enum DatePrecision {
    /**
     * Whole days.
     */
    DAYS,
    /**
     * Whole hours.
     */
    HOURS,
    /**
     * Whole minutes.
     */
    MINUTES,
    /**
     * Whole seconds.
     */
    SECONDS
}
